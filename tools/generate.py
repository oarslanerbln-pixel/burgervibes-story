#!/usr/bin/env python3
"""Generate the FLOW slots of the story plan through the Gemini API.

Google Flow has no public API; the same image models (Nano Banana / Imagen)
are reachable through the official Gemini API, so this script is the
automatable stand-in for "open Flow, paste prompt, download".

Auth: the session's network proxy injects the real key into the
x-goog-api-key header for generativelanguage.googleapis.com (environment
network secret). Locally, GEMINI_API_KEY can be set instead. The key never
lives in this file or in the repo.

Existing files are skipped, so a re-run only fills gaps or retries rejects.
A rejected image is regenerated by deleting it and passing --override with a
refined scene (the art-director step writes those into overrides.json).
"""
import argparse
import base64
import json
import os
import sys
import time
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
API = "https://generativelanguage.googleapis.com/v1beta/models/"
MODELS = {
    # Nano Banana: Gemini image model, supports aspect ratio via imageConfig.
    "nano": "gemini-2.5-flash-image",
    # Imagen 4: the photographic model Flow uses for stills (paid tier only).
    "imagen": "imagen-4.0-generate-001",
}


def post(url, body, timeout=180):
    key = os.environ.get("GEMINI_API_KEY", "injected-by-proxy")
    req = urllib.request.Request(url, data=json.dumps(body).encode(), method="POST",
                                 headers={"Content-Type": "application/json", "x-goog-api-key": key})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.load(r)


def gen_nano(prompt):
    body = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"responseModalities": ["IMAGE"], "imageConfig": {"aspectRatio": "9:16"}},
    }
    res = post(API + MODELS["nano"] + ":generateContent", body)
    for cand in res.get("candidates", []):
        for part in cand.get("content", {}).get("parts", []):
            data = part.get("inlineData") or part.get("inline_data")
            if data:
                return base64.b64decode(data["data"]), data.get("mimeType", "image/png")
    raise RuntimeError("no image in response: " + json.dumps(res)[:400])


def gen_imagen(prompt):
    body = {"instances": [{"prompt": prompt}],
            "parameters": {"sampleCount": 1, "aspectRatio": "9:16", "personGeneration": "dont_allow"}}
    res = post(API + MODELS["imagen"] + ":predict", body)
    preds = res.get("predictions") or []
    if not preds:
        raise RuntimeError("no image in response (often a safety filter): " + json.dumps(res)[:400])
    return base64.b64decode(preds[0]["bytesBase64Encoded"]), preds[0].get("mimeType", "image/png")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--week", type=int)
    p.add_argument("--day")
    p.add_argument("--ids", nargs="*")
    p.add_argument("--model", choices=list(MODELS), default="nano")
    p.add_argument("--media", default=os.path.join(ROOT, "assets", "ai"))
    p.add_argument("--dry-run", action="store_true", help="Only list what would be generated")
    a = p.parse_args()

    plan = json.load(open(os.path.join(HERE, "plan.json"), encoding="utf-8"))
    ov_path = os.path.join(ROOT, "plan", "overrides.json")
    overrides = json.load(open(ov_path, encoding="utf-8")) if os.path.exists(ov_path) else {}
    os.makedirs(a.media, exist_ok=True)
    gen = gen_nano if a.model == "nano" else gen_imagen

    todo = [s for s in plan["slots"] if s["src"] == "FLOW"
            and (not a.week or s["week"] == a.week) and (not a.day or s["day"] == a.day)
            and (not a.ids or s["id"] in a.ids)]
    ok, failed, skipped = [], [], []
    for s in todo:
        out = os.path.join(a.media, s["id"] + ".png")
        if os.path.exists(out):
            skipped.append(s["id"])
            continue
        prompt = plan["style"] + overrides[s["id"]] if s["id"] in overrides else s["prompt"]
        if a.dry_run:
            print(s["id"], "->", prompt[len(plan["style"]):][:90])
            continue
        for attempt in range(3):
            try:
                img, mime = gen(prompt)
                ext = ".jpg" if "jpeg" in mime else ".png"
                out = os.path.join(a.media, s["id"] + ext)
                open(out, "wb").write(img)
                ok.append(s["id"])
                print("ok", s["id"], out, flush=True)
                break
            except urllib.error.HTTPError as e:
                msg = e.read().decode(errors="replace")[:300]
                if e.code in (429, 500, 503) and attempt < 2:
                    time.sleep(8 * (attempt + 1))
                    continue
                failed.append((s["id"], f"HTTP {e.code}: {msg}"))
                break
            except Exception as e:  # network refusal, safety block, malformed reply
                failed.append((s["id"], str(e)[:300]))
                break
    summary = {"generated": ok, "skipped_existing": skipped, "failed": failed}
    print(json.dumps(summary, ensure_ascii=False, indent=1))
    sys.exit(1 if failed and not ok else 0)


if __name__ == "__main__":
    main()
