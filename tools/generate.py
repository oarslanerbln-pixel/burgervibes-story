#!/usr/bin/env python3
"""Generate the FLOW slots of the story plan through the Gemini API.

Google Flow has no public API; the same image models (Nano Banana / Imagen)
are reachable through the official Gemini API, so this script is the
automatable stand-in for "open Flow, paste prompt, download".

Auth, two ways - the key never lives in this file or in the repo:
  - Cloud sessions: the key is a network secret that the proxy injects as
    "Authorization: Bearer". Google's native endpoint rejects API keys sent
    that way, so without GEMINI_API_KEY we call the OpenAI-compatible
    endpoint (/v1beta/openai/images/generations), which accepts them.
  - Laptop: set GEMINI_API_KEY; then the native endpoint is used with the
    x-goog-api-key header and native 9:16 aspect ratio.
Image models are not in Google's free tier (quota 0): the project behind the
key needs billing enabled, otherwise every call returns 429.
Every result is normalised to a 1080x1920 PNG (centre crop), whatever size
the model returns.

Existing files are skipped, so a re-run only fills gaps or retries rejects.
A rejected image is regenerated by deleting it and passing --override with a
refined scene (the art-director step writes those into overrides.json).
"""
import argparse
import base64
import json
import os
import sys
import time
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
API = "https://generativelanguage.googleapis.com/v1beta/models/"
OPENAI_API = "https://generativelanguage.googleapis.com/v1beta/openai/"
MODELS = {
    # Nano Banana: Gemini image model, supports aspect ratio via imageConfig.
    "nano": "gemini-2.5-flash-image",
    # Newer Nano Banana and Nano Banana Pro (sharper, slower, pricier).
    "nano2": "gemini-3.1-flash-image",
    "pro": "gemini-3-pro-image",
    # Imagen 4: the photographic model Flow uses for stills (native endpoint only).
    "imagen": "imagen-4.0-generate-001",
}
LOCAL_KEY = os.environ.get("GEMINI_API_KEY")


def post(url, body, timeout=180):
    headers = {"Content-Type": "application/json"}
    if LOCAL_KEY:
        headers["x-goog-api-key"] = LOCAL_KEY
    # Without a local key we send no auth header: the proxy adds the saved one.
    req = urllib.request.Request(url, data=json.dumps(body).encode(), method="POST", headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.load(r)


def gen_openai_compat(model, prompt):
    body = {"model": model, "prompt": prompt, "n": 1, "response_format": "b64_json", "size": "1024x1792"}
    res = post(OPENAI_API + "images/generations", body)
    data = res.get("data") or []
    if not data or not data[0].get("b64_json"):
        raise RuntimeError("no image in response (often a safety filter): " + json.dumps(res)[:400])
    return base64.b64decode(data[0]["b64_json"]), "image/png"


def to_story_frame(raw, out_path):
    """Centre-crop any returned size to 9:16 and scale to 1080x1920."""
    from io import BytesIO
    from PIL import Image
    im = Image.open(BytesIO(raw)).convert("RGB")
    w, h = im.size
    target = 9 / 16
    if w / h > target:
        nw = int(h * target)
        im = im.crop(((w - nw) // 2, 0, (w - nw) // 2 + nw, h))
    elif w / h < target:
        nh = int(w / target)
        im = im.crop((0, (h - nh) // 2, w, (h - nh) // 2 + nh))
    im.resize((1080, 1920), Image.LANCZOS).save(out_path)


def gen_nano(prompt, model=MODELS["nano"]):
    body = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"responseModalities": ["IMAGE"], "imageConfig": {"aspectRatio": "9:16"}},
    }
    res = post(API + model + ":generateContent", body)
    for cand in res.get("candidates", []):
        for part in cand.get("content", {}).get("parts", []):
            data = part.get("inlineData") or part.get("inline_data")
            if data:
                return base64.b64decode(data["data"]), data.get("mimeType", "image/png")
    raise RuntimeError("no image in response: " + json.dumps(res)[:400])


def gen_imagen(prompt):
    body = {"instances": [{"prompt": prompt}],
            "parameters": {"sampleCount": 1, "aspectRatio": "9:16", "personGeneration": "dont_allow"}}
    res = post(API + MODELS["imagen"] + ":predict", body)
    preds = res.get("predictions") or []
    if not preds:
        raise RuntimeError("no image in response (often a safety filter): " + json.dumps(res)[:400])
    return base64.b64decode(preds[0]["bytesBase64Encoded"]), preds[0].get("mimeType", "image/png")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--week", type=int)
    p.add_argument("--day")
    p.add_argument("--ids", nargs="*")
    p.add_argument("--model", choices=list(MODELS), default="nano")
    p.add_argument("--media", default=os.path.join(ROOT, "assets", "ai"))
    p.add_argument("--dry-run", action="store_true", help="Only list what would be generated")
    a = p.parse_args()

    plan = json.load(open(os.path.join(HERE, "plan.json"), encoding="utf-8"))
    ov_path = os.path.join(ROOT, "plan", "overrides.json")
    overrides = json.load(open(ov_path, encoding="utf-8")) if os.path.exists(ov_path) else {}
    os.makedirs(a.media, exist_ok=True)
    model = MODELS[a.model]
    if a.model == "imagen":
        if not LOCAL_KEY:
            sys.exit("Imagen needs the native endpoint: set GEMINI_API_KEY or use --model nano/nano2/pro")
        gen = gen_imagen
    elif LOCAL_KEY:
        gen = lambda pr: gen_nano(pr, model)  # noqa: E731
    else:
        gen = lambda pr: gen_openai_compat(model, pr)  # noqa: E731

    todo = [s for s in plan["slots"] if s["src"] == "FLOW"
            and (not a.week or s["week"] == a.week) and (not a.day or s["day"] == a.day)
            and (not a.ids or s["id"] in a.ids)]
    ok, failed, skipped = [], [], []
    for s in todo:
        out = os.path.join(a.media, s["id"] + ".png")
        if os.path.exists(out):
            skipped.append(s["id"])
            continue
        prompt = plan["style"] + overrides[s["id"]] if s["id"] in overrides else s["prompt"]
        if a.dry_run:
            print(s["id"], "->", prompt[len(plan["style"]):][:90])
            continue
        for attempt in range(3):
            try:
                img, _mime = gen(prompt)
                to_story_frame(img, out)
                ok.append(s["id"])
                print("ok", s["id"], out, flush=True)
                break
            except urllib.error.HTTPError as e:
                full = e.read().decode(errors="replace")
                free_tier = "free_tier" in full and "limit: 0" in full
                msg = ("FREE_TIER: billing is off for the Google project behind the key" if free_tier
                       else full[:300])
                # The free tier has no image quota at all: retrying never helps.
                if e.code in (429, 500, 503) and attempt < 2 and not free_tier:
                    time.sleep(8 * (attempt + 1))
                    continue
                failed.append((s["id"], f"HTTP {e.code}: {msg}"))
                break
            except Exception as e:  # network refusal, safety block, malformed reply
                failed.append((s["id"], str(e)[:300]))
                break
    summary = {"generated": ok, "skipped_existing": skipped, "failed": failed}
    print(json.dumps(summary, ensure_ascii=False, indent=1))
    sys.exit(1 if failed and not ok else 0)


if __name__ == "__main__":
    main()
